import React, { useState, useRef, useEffect } from 'react';
import { Send, Loader2 } from 'lucide-react';

const MAX_CHAR_LIMIT = 4000;

export default function ChatInput({ onSendMessage, isLoading }) {
  const [text, setText] = useState('');
  const textareaRef = useRef(null);

  // Auto resize textarea height
  useEffect(() => {
    if (textareaRef.current) {
      textareaRef.current.style.height = 'auto';
      textareaRef.current.style.height = `${Math.min(textareaRef.current.scrollHeight, 180)}px`;
    }
  }, [text]);

  const handleSubmit = (e) => {
    e?.preventDefault();
    const trimmed = text.trim();
    if (!trimmed || isLoading) return;

    onSendMessage(trimmed);
    setText('');
    if (textareaRef.current) {
      textareaRef.current.style.height = 'auto';
    }
  };

  const handleKeyDown = (e) => {
    // Send message on Enter without Shift
    if (e.key === 'Enter' && !e.shiftKey) {
      e.preventDefault();
      handleSubmit();
    }
  };

  const charsLeft = MAX_CHAR_LIMIT - text.length;
  const isNearLimit = charsLeft < 300;

  return (
    <div className="input-area-wrapper">
      <form onSubmit={handleSubmit} className="input-box">
        <textarea
          ref={textareaRef}
          value={text}
          onChange={(e) => setText(e.target.value.slice(0, MAX_CHAR_LIMIT))}
          onKeyDown={handleKeyDown}
          placeholder="Ask DevBot anything about code, Docker, Jenkins, or cloud pipelines..."
          rows={1}
          className="input-textarea"
          disabled={isLoading}
          aria-label="Chat input message"
        />

        <div className="input-footer">
          <div className="input-hints">
            <span>Press <strong>Enter</strong> to send, <strong>Shift + Enter</strong> for newline</span>
          </div>

          <div className="input-actions">
            {text.length > 500 && (
              <span className={`char-counter ${isNearLimit ? 'limit-near' : ''}`}>
                {text.length}/{MAX_CHAR_LIMIT}
              </span>
            )}

            <button
              type="submit"
              disabled={!text.trim() || isLoading}
              className="send-button"
              title="Send message"
              aria-label="Send message"
            >
              {isLoading ? <Loader2 size={18} className="animate-spin" /> : <Send size={16} />}
            </button>
          </div>
        </div>
      </form>
      <div className="input-disclaimer">
        DevBot AI integrates with Google Gemini API. Responses are generated by AI.
      </div>
    </div>
  );
}

